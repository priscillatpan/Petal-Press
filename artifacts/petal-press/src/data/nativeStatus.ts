export function getNativeStatus(scientificName: string): NativeStatus {
  const lower = scientificName.toLowerCase();
  for (const entry of NATIVE_STATUS_MAP) {
    if (lower.includes(entry.match.toLowerCase())) return entry.status;
  }
  return "unknown";
}

