const { data: flowers, error } = await supabase.from("flowers").select("id,common_name,latin_name,meaning,nickname");
if (error) { console.error("Fetch error:", error.message); process.exit(1); }

console.log(`Fetched ${flowers.length} flowers`);

let updated = 0, skipped = 0;
for (const row of flowers) {
  const lookup = lookupFloriography(row.common_name, row.latin_name || "");
  const needsUpdate = row.meaning !== lookup.meaning || row.nickname !== lookup.nickname;
  if (!needsUpdate) { skipped++; continue; }
  console.log(`  Updating: ${row.common_name}`);
  console.log(`    meaning:  "${row.meaning}" → "${lookup.meaning}"`);
  console.log(`    nickname: "${row.nickname}" → "${lookup.nickname}"`);
  const { error: updateErr } = await supabase
    .from("flowers")
    .update({ meaning: lookup.meaning, nickname: lookup.nickname })
    .eq("id", row.id);
  if (updateErr) { console.error(`  ✗ Failed: ${updateErr.message}`); }
  else { updated++; }
}

console.log(`\nDone — ${updated} updated, ${skipped} already correct`);
